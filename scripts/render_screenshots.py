"""Render high-resolution screenshots directly from examples/sample_report.xlsx.

This script parses the committed workbook using openpyxl and generates faithful visual
representations of the sheets as PNG images in examples/screenshots/.
"""

from __future__ import annotations

import os
from pathlib import Path
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.patches as patches
import openpyxl

# Set matplotlib config dir to /tmp if needed
os.environ["MPLCONFIGDIR"] = "/tmp/matplotlib_cache"


import textwrap


def render_executive_summary(wb: openpyxl.Workbook, out_path: Path) -> None:
    """Render 01_EXECUTIVE_SUMMARY sheet."""
    ws = wb["01_EXECUTIVE_SUMMARY"]

    fig = plt.figure(figsize=(15, 9.5), dpi=200)
    fig.patch.set_facecolor("#FAF9F6")
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_facecolor("#FAF9F6")
    ax.axis("off")

    # Title & Subtitle
    title = ws.cell(row=1, column=1).value or "UMKM Retail Analytics — Executive Performance Summary"
    subtitle = ws.cell(row=2, column=1).value or ""
    ax.text(0.03, 0.955, title, fontsize=18, fontweight="bold", color="#7A1C24", transform=ax.transAxes)
    ax.text(0.03, 0.925, subtitle, fontsize=9.5, color="#555555", transform=ax.transAxes)

    # Top KPI Cards
    kpi_cards = [
        ("TOTAL NET SALES", f"Rp {ws.cell(row=5, column=1).value:,.0f}", "#7A1C24"),
        ("TOTAL TRANSACTIONS", f"{ws.cell(row=5, column=3).value:,}", "#1B4D3E"),
        ("AVG BASKET (ATV)", f"Rp {ws.cell(row=5, column=5).value:,.0f}", "#2C3E50"),
        ("TOTAL UNITS SOLD", f"{ws.cell(row=5, column=7).value:,}", "#8E44AD"),
        ("REORDER ALERTS", f"{ws.cell(row=5, column=9).value} SKUs", "#C0392B"),
    ]

    card_width = 0.176
    card_gap = 0.015
    start_x = 0.03
    card_y = 0.81
    card_height = 0.090

    for i, (label, val, accent_color) in enumerate(kpi_cards):
        cx = start_x + i * (card_width + card_gap)
        # Background box
        rect = patches.FancyBboxPatch(
            (cx, card_y), card_width, card_height,
            boxstyle="round,pad=0.010",
            facecolor="#FFFFFF", edgecolor="#D5D5D5", linewidth=1.1,
            transform=ax.transAxes
        )
        ax.add_patch(rect)
        # Accent top bar
        bar = patches.Rectangle((cx, card_y + card_height - 0.006), card_width, 0.006, facecolor=accent_color, transform=ax.transAxes)
        ax.add_patch(bar)
        # Texts
        ax.text(cx + 0.008, card_y + 0.056, label, fontsize=7.5, fontweight="bold", color="#666666", transform=ax.transAxes)
        ax.text(cx + 0.008, card_y + 0.018, val, fontsize=12, fontweight="bold", color="#222222", transform=ax.transAxes)

    # Section 1: Executive Observations (Left Side Panel)
    obs_box = patches.FancyBboxPatch(
        (0.03, 0.13), 0.46, 0.63,
        boxstyle="round,pad=0.012",
        facecolor="#FFFFFF", edgecolor="#DDDDDD", linewidth=1.1,
        transform=ax.transAxes
    )
    ax.add_patch(obs_box)
    top_obs_bar = patches.Rectangle((0.03, 0.755), 0.46, 0.005, facecolor="#7A1C24", transform=ax.transAxes)
    ax.add_patch(top_obs_bar)

    header_obs = ws.cell(row=8, column=1).value or "Key Analytical Observations & Strategic Action Considerations"
    ax.text(0.045, 0.725, header_obs, fontsize=10.5, fontweight="bold", color="#7A1C24", transform=ax.transAxes)

    obs_y = 0.685
    for r in range(9, 15):
        val = ws.cell(row=r, column=1).value
        if not val:
            continue
        wrapped = textwrap.wrap(str(val), width=58)
        for line_idx, line in enumerate(wrapped):
            prefix = "• " if line_idx == 0 else "   "
            ax.text(0.045, obs_y, f"{prefix}{line}", fontsize=8.2, color="#333333", transform=ax.transAxes)
            obs_y -= 0.023
        obs_y -= 0.010

    # Disclaimer at bottom left
    disclaimer = ws.cell(row=25, column=1).value or "* Disclaimer: Generated by UMKM Retail Analytics Engine."
    disc_wrapped = textwrap.wrap(str(disclaimer), width=65)
    disc_y = 0.09
    for d_line in disc_wrapped:
        ax.text(0.03, disc_y, d_line, fontsize=7.5, fontstyle="italic", color="#777777", transform=ax.transAxes)
        disc_y -= 0.022

    # Section 2: Monthly Sales Performance Table & Bar Chart (Right Side)
    ax.text(0.53, 0.765, "Monthly Revenue Performance (April – Sept 2026)", fontsize=11, fontweight="bold", color="#7A1C24", transform=ax.transAxes)

    months = []
    net_sales = []
    orders = []
    atvs = []
    moms = []

    for r in range(18, 24):
        m = ws.cell(row=r, column=1).value
        ns = ws.cell(row=r, column=2).value
        ord_c = ws.cell(row=r, column=3).value
        atv = ws.cell(row=r, column=4).value
        mom = ws.cell(row=r, column=5).value
        if m:
            months.append(str(m))
            net_sales.append(float(ns or 0))
            orders.append(int(ord_c or 0))
            atvs.append(float(atv or 0))
            moms.append(f"{float(mom or 0)*100:+.1f}%" if float(mom or 0) != 0 else "0.0%")

    # Chart with headroom
    chart_ax = fig.add_axes([0.53, 0.44, 0.44, 0.29])
    chart_ax.set_facecolor("#FFFFFF")
    bars = chart_ax.bar(months, [ns / 1e6 for ns in net_sales], color="#7A1C24", width=0.55, edgecolor="#551016")
    chart_ax.set_ylabel("Net Sales (Juta Rp)", fontsize=8.5, color="#444444")
    chart_ax.tick_params(axis="both", labelsize=8)
    chart_ax.grid(axis="y", linestyle="--", alpha=0.5)

    max_ns_juta = max(net_sales) / 1e6 if net_sales else 12
    chart_ax.set_ylim(0, max_ns_juta * 1.20)

    for bar, ns in zip(bars, net_sales):
        yval = bar.get_height()
        chart_ax.text(bar.get_x() + bar.get_width() / 2.0, yval + 0.35, f"Rp {yval:.1f}M", ha="center", va="bottom", fontsize=7.5, fontweight="bold", color="#333333")

    # Table under chart
    table_ax = fig.add_axes([0.53, 0.11, 0.44, 0.27])
    table_ax.axis("off")
    table_data = [
        [m, f"Rp {ns:,.0f}", f"{o:,}", f"Rp {atv:,.0f}", mom]
        for m, ns, o, atv, mom in zip(months, net_sales, orders, atvs, moms)
    ]
    headers = ["Month", "Net Sales", "Orders", "ATV", "MoM"]
    tbl = table_ax.table(cellText=table_data, colLabels=headers, loc="center", cellLoc="center")
    tbl.auto_set_font_size(False)
    tbl.set_fontsize(8)
    tbl.scale(1, 1.45)

    for j in range(len(headers)):
        tbl[0, j].set_facecolor("#7A1C24")
        tbl[0, j].set_text_props(color="white", fontweight="bold")
    for row_idx in range(1, len(table_data) + 1):
        bg = "#F7F6F2" if row_idx % 2 == 0 else "#FFFFFF"
        for col_idx in range(len(headers)):
            tbl[row_idx, col_idx].set_facecolor(bg)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(out_path, dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(f"[OK] Generated {out_path}")


def render_sales_analysis(wb: openpyxl.Workbook, out_path: Path) -> None:
    """Render 02_SALES_OVERVIEW sheet."""
    ws = wb["02_SALES_OVERVIEW"]

    fig = plt.figure(figsize=(15, 9.5), dpi=200)
    fig.patch.set_facecolor("#FAF9F6")

    # Title & Subtitle from sheet
    title = ws.cell(row=1, column=1).value or "Sales & Revenue Overview"
    subtitle = ws.cell(row=2, column=1).value or "Chronological monthly trends, channel contribution, and category sales performance."
    fig.text(0.03, 0.955, title, fontsize=18, fontweight="bold", color="#7A1C24")
    fig.text(0.03, 0.925, f"{subtitle} | Source: Synthetic Dataset", fontsize=9.5, color="#555555")

    # 1. Channel Breakdown Pie Chart (Dynamically read rows 16 to 18)
    channels = []
    channel_sales = []
    for r in range(16, 19):
        ch_name = ws.cell(row=r, column=1).value
        ch_val = ws.cell(row=r, column=2).value
        if ch_name and ch_val is not None:
            channels.append(str(ch_name))
            channel_sales.append(float(ch_val))

    colors = ["#7A1C24", "#2E6B56", "#D98829", "#2C3E50"][:len(channels)]

    pie_ax = fig.add_axes([0.05, 0.51, 0.40, 0.36])
    wedges, texts, autotexts = pie_ax.pie(
        channel_sales,
        labels=channels,
        autopct="%1.1f%%",
        startangle=140,
        colors=colors,
        textprops={"fontsize": 9},
        wedgeprops={"edgecolor": "white", "linewidth": 2}
    )
    for at in autotexts:
        at.set_color("white")
        at.set_fontweight("bold")
    channel_title = ws.cell(row=14, column=1).value or "Sales Performance by Channel"
    pie_ax.set_title(f"{channel_title} (% Net Sales)", fontsize=10.5, fontweight="bold", color="#333333", pad=10)

    # 2. Category Breakdown Horizontal Bar Chart (Dynamically read rows 23 to 27)
    categories = []
    cat_revenue = []
    for r in range(23, 28):
        cat_name = ws.cell(row=r, column=1).value
        cat_val = ws.cell(row=r, column=2).value
        if cat_name and cat_val is not None:
            categories.append(str(cat_name))
            cat_revenue.append(float(cat_val) / 1e6)  # in Millions Rp

    cat_ax = fig.add_axes([0.53, 0.51, 0.42, 0.36])
    cat_ax.set_facecolor("#FFFFFF")
    bars = cat_ax.barh(categories[::-1], cat_revenue[::-1], color="#2C3E50", edgecolor="#1A252F", height=0.58)
    cat_ax.set_xlabel("Net Sales (Rp Juta)", fontsize=8.5, color="#444444")
    category_title = ws.cell(row=21, column=1).value or "Sales Performance by Product Category"
    cat_ax.set_title(category_title, fontsize=10.5, fontweight="bold", color="#333333", pad=10)
    cat_ax.tick_params(axis="both", labelsize=8)
    cat_ax.grid(axis="x", linestyle="--", alpha=0.5)

    max_cat = max(cat_revenue) if cat_revenue else 25
    cat_ax.set_xlim(0, max_cat * 1.25)

    for bar, val in zip(bars, cat_revenue[::-1]):
        cat_ax.text(bar.get_width() + 0.45, bar.get_y() + bar.get_height() / 2.0, f"Rp {val:.2f}M", va="center", fontsize=8, fontweight="bold", color="#333333")

    # 3. Monthly Financial Table (Full Width Bottom) - Dynamically read from sheet
    tbl_ax = fig.add_axes([0.05, 0.08, 0.90, 0.36])
    tbl_ax.axis("off")

    headers = ["Month", "Gross Sales", "Discounts", "Net Sales", "Orders", "Units Sold", "ATV", "MoM Growth"]
    data = []

    # Dynamic totals accumulator
    tot_gross = sum(float(ws.cell(row=r, column=2).value or 0) for r in range(5, 11))
    tot_disc = sum(float(ws.cell(row=r, column=3).value or 0) for r in range(5, 11))
    tot_net = sum(float(ws.cell(row=r, column=4).value or 0) for r in range(5, 11))
    tot_ords = int(ws.cell(row=11, column=5).value or sum(int(ws.cell(row=r, column=5).value or 0) for r in range(5, 11)))
    tot_units = sum(int(ws.cell(row=r, column=6).value or 0) for r in range(5, 11))
    tot_atv = float(ws.cell(row=11, column=7).value or (tot_net / tot_ords if tot_ords else 0))

    for r in range(5, 11):
        m = ws.cell(row=r, column=1).value
        gs = ws.cell(row=r, column=2).value
        disc = ws.cell(row=r, column=3).value
        ns = ws.cell(row=r, column=4).value
        ords = ws.cell(row=r, column=5).value
        units = ws.cell(row=r, column=6).value
        atv = ws.cell(row=r, column=7).value
        mom = ws.cell(row=r, column=8).value
        if m:
            data.append([
                str(m),
                f"Rp {float(gs):,.0f}" if gs else "-",
                f"Rp {float(disc):,.0f}" if disc else "-",
                f"Rp {float(ns):,.0f}" if ns else "-",
                f"{int(ords):,}" if ords else "-",
                f"{int(units):,}" if units else "-",
                f"Rp {float(atv):,.2f}" if atv else "-",
                f"{float(mom)*100:+.1f}%" if mom != 0 else "0.0%"
            ])

    # Append summary row dynamically
    data.append([
        "TOTAL / SUMMARY",
        f"Rp {tot_gross:,.0f}",
        f"Rp {tot_disc:,.0f}",
        f"Rp {tot_net:,.0f}",
        f"{tot_ords:,}",
        f"{tot_units:,}",
        f"Rp {tot_atv:,.2f}",
        "-"
    ])

    table = tbl_ax.table(cellText=data, colLabels=headers, loc="center", cellLoc="center")
    table.auto_set_font_size(False)
    table.set_fontsize(8.5)
    table.scale(1, 1.40)

    for j in range(len(headers)):
        table[0, j].set_facecolor("#7A1C24")
        table[0, j].set_text_props(color="white", fontweight="bold")
    for r_idx in range(1, len(data) + 1):
        bg = "#F2EBE5" if r_idx == len(data) else ("#FAF9F6" if r_idx % 2 == 0 else "#FFFFFF")
        for c_idx in range(len(headers)):
            cell = table[r_idx, c_idx]
            cell.set_facecolor(bg)
            if r_idx == len(data):
                cell.set_text_props(fontweight="bold")

    plt.savefig(out_path, dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(f"[OK] Generated {out_path}")


def render_data_quality(wb: openpyxl.Workbook, out_path: Path) -> None:
    """Render 07_DATA_QUALITY sheet."""
    ws = wb["07_DATA_QUALITY"]

    fig = plt.figure(figsize=(15, 10.5), dpi=200)
    fig.patch.set_facecolor("#FAF9F6")

    # Title & Subtitle from sheet
    title = ws.cell(row=1, column=1).value or "Data Quality Audit & Hygiene Report"
    subtitle = ws.cell(row=2, column=1).value or "Before-and-after reconciliation of input records, anomalies detected, and quarantine audit trail."
    fig.text(0.03, 0.962, title, fontsize=18, fontweight="bold", color="#7A1C24")
    fig.text(0.03, 0.938, subtitle, fontsize=9.5, color="#555555")

    # Section Headers
    title_tbl1 = ws.cell(row=3, column=1).value or "Data Ingestion & Cleaning Metrics"
    fig.text(0.03, 0.906, title_tbl1, fontsize=10.5, fontweight="bold", color="#7A1C24")

    # Ingestion & Hygiene Metrics Table (Left Top)
    tbl1_ax = fig.add_axes([0.03, 0.49, 0.54, 0.40])
    tbl1_ax.axis("off")

    headers1 = ["Quality Metric", "Count / Value", "Operational Meaning & Rule Applied"]
    data1 = []
    for r in range(5, 17):
        metric = ws.cell(row=r, column=1).value
        val = ws.cell(row=r, column=2).value
        rule = ws.cell(row=r, column=3).value
        if metric:
            if isinstance(val, (int, float)):
                v_str = f"{val:,}"
            else:
                v_str = str(val or "")
            wrapped_rule = textwrap.fill(str(rule or ""), width=44)
            data1.append([str(metric), v_str, wrapped_rule])

    table1 = tbl1_ax.table(
        cellText=data1,
        colLabels=headers1,
        colWidths=[0.31, 0.17, 0.52],
        loc="center",
        cellLoc="left"
    )
    table1.auto_set_font_size(False)
    table1.set_fontsize(7.2)
    table1.scale(1, 1.40)

    for j in range(len(headers1)):
        table1[0, j].set_facecolor("#7A1C24")
        table1[0, j].set_text_props(color="white", fontweight="bold")
    for r_idx in range(1, len(data1) + 1):
        bg = "#F7F6F2" if r_idx % 2 == 0 else "#FFFFFF"
        for c_idx in range(len(headers1)):
            table1[r_idx, c_idx].set_facecolor(bg)

    # Reconciliation Visual Diagram (Right Top) - Dynamically read counts from worksheet
    raw_rows = ws.cell(row=5, column=2).value or 1788
    clean_rows = ws.cell(row=6, column=2).value or 1770
    dup_rows = ws.cell(row=8, column=2).value or 6
    quar_rows = ws.cell(row=9, column=2).value or 12

    diag_ax = fig.add_axes([0.61, 0.49, 0.36, 0.40])
    diag_ax.set_facecolor("#FFFFFF")
    diag_ax.axis("off")

    box_rect = patches.FancyBboxPatch(
        (0.04, 0.04), 0.92, 0.92,
        boxstyle="round,pad=0.02",
        facecolor="#FDFBF7", edgecolor="#7A1C24", linewidth=1.5
    )
    diag_ax.add_patch(box_rect)
    diag_ax.text(0.50, 0.86, "STRICT ROW ACCOUNTING INVARIANT", ha="center", fontsize=9.5, fontweight="bold", color="#7A1C24")
    diag_ax.text(0.50, 0.73, f"Raw Input Rows ({raw_rows:,})\n100.0%", ha="center", fontsize=10.5, fontweight="bold", color="#2C3E50")
    diag_ax.text(0.50, 0.61, "▼", ha="center", fontsize=13, color="#888888")

    clean_pct = (clean_rows / raw_rows * 100) if raw_rows else 0
    quar_pct = (quar_rows / raw_rows * 100) if raw_rows else 0
    dup_pct = (dup_rows / raw_rows * 100) if raw_rows else 0

    diag_ax.text(0.20, 0.40, f"Clean Data\n{clean_rows:,} ({clean_pct:.2f}%)\n[ACCEPTED]", ha="center", fontsize=8, fontweight="bold", color="#1B4D3E")
    diag_ax.text(0.37, 0.40, "+", ha="center", fontsize=12, color="#888888")
    diag_ax.text(0.52, 0.40, f"Quarantined\n{quar_rows:,} ({quar_pct:.2f}%)\n[AUDITED]", ha="center", fontsize=8, fontweight="bold", color="#C0392B")
    diag_ax.text(0.68, 0.40, "+", ha="center", fontsize=12, color="#888888")
    diag_ax.text(0.82, 0.40, f"Duplicates\n{dup_rows:,} ({dup_pct:.2f}%)\n[DEDUPED]", ha="center", fontsize=8, fontweight="bold", color="#7F8C8D")

    reconciled_ok = (raw_rows == clean_rows + quar_rows + dup_rows)
    proof_text = f"Reconciliation Proof: {raw_rows:,} == {clean_rows:,} + {quar_rows:,} + {dup_rows:,}\nStatus: {'100% Reconciled (Zero Silent Drops)' if reconciled_ok else 'Reconciliation Mismatch'}"
    diag_ax.text(0.50, 0.16, proof_text, ha="center", fontsize=8, color="#333333", fontweight="bold")

    # Quarantine Records Table (Bottom Full Width)
    title_tbl2 = ws.cell(row=19, column=1).value or "Audit Sample of Quarantined Records (Excluded from Analytics)"
    fig.text(0.03, 0.442, title_tbl2, fontsize=10.5, fontweight="bold", color="#7A1C24")

    tbl2_ax = fig.add_axes([0.03, 0.04, 0.94, 0.38])
    tbl2_ax.axis("off")

    headers2 = ["Transaction ID", "Raw Date", "SKU", "Qty", "Price", "Quarantine Reason"]
    data2 = []
    # Read rows 21 to 32 (all quarantined sample rows)
    for r in range(21, 33):
        row_vals = [ws.cell(row=r, column=c).value for c in range(1, 7)]
        if any(v is not None for v in row_vals):
            tid, dt, sku, qty, pr, reas = row_vals
            wrapped_reas = textwrap.fill(str(reas or ""), width=58)
            data2.append([
                str(tid or "-"),
                str(dt or "-"),
                str(sku or "-"),
                str(qty or "-"),
                str(pr or "-"),
                wrapped_reas
            ])

    table2 = tbl2_ax.table(
        cellText=data2,
        colLabels=headers2,
        colWidths=[0.13, 0.15, 0.10, 0.06, 0.08, 0.48],
        loc="center",
        cellLoc="left"
    )
    table2.auto_set_font_size(False)
    table2.set_fontsize(7.2)
    table2.scale(1, 1.48)

    for j in range(len(headers2)):
        table2[0, j].set_facecolor("#7A1C24")
        table2[0, j].set_text_props(color="white", fontweight="bold")
    for r_idx in range(1, len(data2) + 1):
        bg = "#FDF7F7" if r_idx % 2 == 0 else "#FFFFFF"
        for c_idx in range(len(headers2)):
            table2[r_idx, c_idx].set_facecolor(bg)

    plt.savefig(out_path, dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(f"[OK] Generated {out_path}")


def main() -> None:
    repo_root = Path(__file__).resolve().parent.parent
    sample_report = repo_root / "examples" / "sample_report.xlsx"
    screenshot_dir = repo_root / "examples" / "screenshots"

    if not sample_report.exists():
        raise FileNotFoundError(f"Workbook not found at {sample_report}")

    wb = openpyxl.load_workbook(sample_report, data_only=True)

    render_executive_summary(wb, screenshot_dir / "executive-summary.png")
    render_sales_analysis(wb, screenshot_dir / "sales-analysis.png")
    render_data_quality(wb, screenshot_dir / "data-quality.png")
    print("All screenshots generated successfully.")


if __name__ == "__main__":
    main()

